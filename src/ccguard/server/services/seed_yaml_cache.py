"""Кеш разбора сид-YAML в пределах процесса.

Пять YAML-справочников разбираются при каждом старте сервера — это ~140 мс,
почти половина стоимости всего сидирования, и работа полностью повторная:
файлы на диске между стартами не меняются.

Кеш держит разобранный результат по ключу «путь + время правки + размер».
Правка файла меняет mtime/размер → ключ другой → файл перечитывается. То есть
это не «прочитать один раз и забыть»: свежесть сохраняется, экономится только
повторный разбор одного и того же содержимого.

Кеш живёт в памяти процесса и умирает вместе с ним, так что на поведение
рестарта он не влияет. Ошибку чтения/разбора не кешируем: следующий вызов
попробует снова (файл могли чинить прямо сейчас).
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

# (путь, mtime_ns, размер) → разобранный YAML
_cache: dict[tuple[str, int, int], Any] = {}


def load_yaml(path: Path) -> Any:
    """Разобрать YAML с кешированием по содержимому файла.

    Возвращает то же, что ``yaml.safe_load``. Пробрасывает OSError/YAMLError —
    вызывающая сторона уже умеет их обрабатывать (сид-загрузчики логируют и
    пропускают загрузку, не роняя старт).
    """
    st = path.stat()  # OSError пробрасываем: файла нет — это ответ вызывающему
    key = (str(path), st.st_mtime_ns, st.st_size)
    if key in _cache:
        return _cache[key]
    data = yaml.safe_load(path.read_text())
    _cache[key] = data
    return data


def clear() -> None:
    """Сбросить кеш (для тестов, которые правят сид-файлы на лету)."""
    _cache.clear()
