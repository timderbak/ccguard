#!/usr/bin/env bash
# Сборка самостоятельных исполняемых файлов агента.
#
# Зачем: шим сейчас вызывает python из виртуального окружения. Атакующий,
# работающий под тем же пользователем, имеет право писать в это окружение —
# значит может подменить модуль, который шим вызовет, и защита исполнит его
# код. Файл под правами администратора закрывает подмену самого шима, но не
# того, что шим запускает. Самостоятельный файл убирает это звено целиком:
# исполняется он, а не интерпретатор с подменяемыми модулями.
#
# Режим сборки — ОДНА ПАПКА, а не один файл. Однофайловая сборка при КАЖДОМ
# запуске распаковывает себя во временный каталог; для проверки перед каждым
# вызовом инструмента это сотни миллисекунд сверху и гарантированный выход за
# бюджет задержки. Папка стартует без распаковки.
#
#   ./scripts/build-agent-binaries.sh [выходной каталог]
#
# По умолчанию собирается в dist/. Готовое содержимое кладут на машине в
# /opt/ccguard/bin — этот путь зашит в шим как приоритетный.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/dist}"
WORK="$OUT/.build"
PY="${PYTHON:-$ROOT/.venv/bin/python}"

if [ ! -x "$PY" ]; then
    echo "не найден интерпретатор: $PY (задайте PYTHON=...)" >&2
    exit 1
fi
if ! "$PY" -c "import PyInstaller" 2>/dev/null; then
    echo "нет PyInstaller: установите зависимости для разработки (pip install -e '.[dev]')" >&2
    exit 1
fi

build_one() {
    local name="$1" entry="$2"
    echo "==> сборка $name"
    "$PY" -m PyInstaller \
        --noconfirm --clean \
        --onedir \
        --name "$name" \
        --distpath "$OUT" \
        --workpath "$WORK" \
        --specpath "$WORK" \
        --console \
        --paths "$ROOT/src" \
        "$ROOT/src/ccguard/agent/$entry"
}

# Проверка перед вызовом инструмента: попадает в бюджет задержки, поэтому
# собирается первой и замеряется ниже.
build_one ccguard-enforce-bin enforce_main.py
# Наблюдение после вызова: бюджета не имеет, но живёт по тем же правилам.
build_one ccguard-audit-bin audit_main.py

echo
echo "==> замер задержки проверки"
# Сборка проверяется замером, а не принимается на веру: не влезающая в бюджет
# сборка ломает работу с инструментом на всех машинах разом, и узнать об этом
# от разработчиков хуже, чем от скрипта.
BIN="$OUT/ccguard-enforce-bin/ccguard-enforce-bin"
if [ ! -x "$BIN" ]; then
    echo "исполняемый файл не собрался: $BIN" >&2
    exit 1
fi
if ! "$ROOT/scripts/measure-hook-latency.sh" "$BIN"; then
    echo >&2
    echo "сборку в таком виде раскатывать нельзя: она медленнее текущего пути," >&2
    echo "а задержку проверки разработчик ждёт лично при каждом вызове." >&2
    exit 1
fi

echo
echo "готово. Содержимое $OUT/ccguard-enforce-bin и $OUT/ccguard-audit-bin"
echo "кладут на машине в /opt/ccguard/bin (см. страницу «Раскатка»)."
